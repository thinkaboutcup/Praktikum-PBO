
package Pertemuan5;


public class Perbandingan {
     public static void main(String[] args) {

        int i = 5;

        System.out.println("Nilai i++: " + i++);
        System.out.println("Nilai i sekarang: " + i);

        int j = 5;

        System.out.println("Nilai ++j: " + (++j));
        System.out.println("Nilai j sekarang: " + j);

    }
}
